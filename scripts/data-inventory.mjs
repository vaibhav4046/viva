#!/usr/bin/env node
/**
 * Data inventory. Greps the source for every place VIVA touches a cookie,
 * browser storage, an analytics call, an upload, a database write or an outbound
 * host, and writes docs/evidence/data-inventory.md. The privacy page is written
 * from that file, so a claim on the page that the inventory does not show is a
 * claim to remove.
 *
 *   node scripts/data-inventory.mjs           write the file
 *   node scripts/data-inventory.mjs --check   fail if the committed file is stale
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SKIP_DIR = new Set(["node_modules", ".next", ".git", "docs", "logs", "tests", "design"]);
const EXT = /\.(ts|tsx|mjs|mts|js)$/;

function walk(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP_DIR.has(e.name)) walk(path.join(dir, e.name), acc);
    } else if (EXT.test(e.name)) acc.push(path.join(dir, e.name));
  }
  return acc;
}

const files = ["src", "scripts"].flatMap((d) => (fs.existsSync(d) ? walk(d) : [])).filter((f) => !/data-inventory\.mjs$|src[\\/]app[\\/]privacy[\\/]page\.tsx$/.test(f)); // the privacy page is written from this file, so it is not evidence for itself
const lines = files.map((f) => ({ f: f.split(path.sep).join("/"), text: fs.readFileSync(f, "utf8").split(/\r?\n/) }));

function hits(re, { exclude } = {}) {
  const out = [];
  for (const { f, text } of lines) {
    if (exclude && exclude.test(f)) continue;
    text.forEach((line, i) => {
      if (re.test(line) && !/^\s*(\*|\/\/)/.test(line)) out.push({ f, n: i + 1, line: line.trim().slice(0, 110) });
    });
  }
  return out;
}

const CATEGORIES = [
  {
    title: "Cookies",
    re: /Set-Cookie|DEMO_COOKIE\s*=|=\$\{fresh\};|cookies\(\)\.set|document\.cookie/,
    note: "Server-set identity cookie only. Attributes are printed from the source line.",
  },
  { title: "localStorage", re: /localStorage\.(get|set|remove)Item/, note: "Keys are chosen by the code that calls it." },
  { title: "sessionStorage", re: /sessionStorage/, note: "None if the table is empty." },
  {
    title: "IndexedDB and Cache API",
    re: /indexedDB|caches\.open/,
    note: "None if the table is empty.",
  },
  {
    title: "Analytics and tracking",
    re: /@vercel\/analytics|gtag|posthog|plausible|mixpanel|segment|sentry|logEvent\(/,
    note: "logEvent counts events in server or browser memory. Nothing in this table sends them anywhere.",
    exclude: /analytics\.ts$/,
  },
  { title: "Uploads and ingest", re: /formData\(\)|pdf-parse|new File\b|multipart/, note: "Routes and libraries that read a learner's material." },
  {
    title: "Database and file writes",
    re: /INSERT INTO|UPDATE \w+ SET|DELETE FROM|writeFile|appendFile|\.query\(/,
    note: "Postgres when DATABASE_URL is set; otherwise a file store (in /tmp on Vercel).",
    exclude: /(migrations|seed|probe|smoke|live-)/,
  },
  { title: "Deletion", re: /deleteUserData|DELETE FROM/, note: "How a learner's data is removed." },
  {
    title: "Outbound hosts",
    re: /https?:\/\/[a-z0-9.-]+\.[a-z]{2,}/i,
    note: "Every literal host in shipped code. Host names taken from environment variables are listed under LLM providers.",
    exclude: /(scripts\/api-probes|seed-corpus|www\.w3\.org|creativecommons|example\.ac\.uk|github\.com|vercel\.app)/,
  },
  { title: "LLM providers", re: /LLM_BASE_URL|LLM_FALLBACKS|AI_PROVIDER/, note: "Passage text and answers go to the providers configured here. Names come from deployment configuration." },
  { title: "Fetches of learner-supplied URLs", re: /VIVA-study-bot|fetchUrl|safeFetch/, note: "The server fetches a page the learner names." },
];

const parts = [];
parts.push("# Data inventory\n");
parts.push("Generated by `node scripts/data-inventory.mjs` from the source tree. Do not edit by hand.\n");
parts.push(`Files scanned: ${files.length} (src and scripts, tests excluded).\n`);

const summary = [];
for (const c of CATEGORIES) {
  const h = hits(c.re, { exclude: c.exclude });
  summary.push(`| ${c.title} | ${h.length} |`);
  parts.push(`## ${c.title}\n`);
  parts.push(`${c.note}\n`);
  if (h.length === 0) parts.push("No matches.\n");
  else {
    parts.push("| File | Line | Code |\n|---|---|---|");
    for (const x of h.slice(0, 40)) parts.push(`| ${x.f} | ${x.n} | \`${x.line.replace(/\|/g, "\\|").replace(/`/g, "'")}\` |`);
    if (h.length > 40) parts.push(`\n${h.length - 40} more matches not shown.`);
    parts.push("");
  }
}

parts.splice(3, 0, "| Category | Matches |\n|---|---|\n" + summary.join("\n") + "\n");
const body = parts.join("\n") + "\n";

const target = path.join(ROOT, "docs", "evidence", "data-inventory.md");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (cur !== body) {
    console.error("data-inventory.md is stale: run node scripts/data-inventory.mjs");
    process.exit(1);
  }
  console.log("data-inventory.md is current");
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body, "utf8");
  console.log(`wrote ${path.relative(ROOT, target)}: ${CATEGORIES.map((c, i) => summary[i].replace(/[|]/g, "").trim()).join("; ")}`);
}
